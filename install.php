if ($step === 2 && $_SERVER['REQUEST_METHOD'] === 'POST') {
    $cfg = [
        'DB_HOST'          => trim($_POST['db_host'] ?? 'localhost'),
        'DB_USER'          => trim($_POST['db_user'] ?? ''),
        'DB_PASS'          => trim($_POST['db_pass'] ?? ''),
        'DB_NAME'          => trim($_POST['db_name'] ?? ''),
        'DB_PREFIX'        => '',
        'TENANT_DB_HOST'   => trim($_POST['db_host'] ?? 'localhost'),
        'TENANT_POOL_SIZE' => 50,
    ];

    if (!$cfg['DB_USER'] || !$cfg['DB_NAME']) {
        $errors[] = 'Database username and name are required.';
        $step = 2;
    } else {
        // Write env.php
        $out  = "<?php\n/**\n * Auto-generated by RosmonSMS Installer — " . date('Y-m-d H:i:s') . "\n */\nreturn [\n";
        foreach ($cfg as $k => $v) {
            $out .= "    '{$k}' => " . (is_int($v) ? $v : "'" . addslashes($v) . "'") . ",\n";
        }
        $out .= "];\n";
        file_put_contents(__DIR__ . '/config/env.php', $out);

        // Test connection
        try {
            $testPdo = new PDO(
                "mysql:host={$cfg['DB_HOST']};dbname={$cfg['DB_NAME']};charset=utf8mb4",
                $cfg['DB_USER'], $cfg['DB_PASS'],
                [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
            );
            $success[] = "Connected to supervisor database '{$cfg['DB_NAME']}' successfully.";
            header('Location: install.php?step=3');
            exit;
        } catch (PDOException $e) {
            $errors[] = "Cannot connect to '{$cfg['DB_NAME']}': " . $e->getMessage();
            $step = 2;
        }
    }
}

// ── Step 3: Install supervisor schema ─────────────────────────────────
if ($step === 3 && $_SERVER['REQUEST_METHOD'] === 'POST') {
    try {
        // Force reload config by using getSupervisorConnection
        $pdo = TenantManager::getSupervisorConnection();

        // Import supervisor schema
        $schemaFile = __DIR__ . '/database/supervisor_schema_utf8.sql';
        if (!file_exists($schemaFile)) {
            $schemaFile = __DIR__ . '/database/supervisor_schema.sql';
        }
        if (!file_exists($schemaFile)) {
            throw new Exception('Supervisor schema file not found. Ensure database/supervisor_schema_utf8.sql exists.');
        }

        TenantManager::runSqlFile($pdo, $schemaFile);
        $success[] = "Supervisor schema imported successfully.";

        // Create super admin
        $adminEmail = trim($_POST['admin_email'] ?? 'admin@rosmonsms.com');
        $adminPass  = trim($_POST['admin_pass']  ?? 'Admin@12345');
        $adminName  = trim($_POST['admin_name']  ?? 'Super Admin');

        if (strlen($adminPass) < 8) {
            throw new Exception('Admin password must be at least 8 characters.');
        }

        $hashedPass = password_hash($adminPass, PASSWORD_DEFAULT);

        // Ensure users table exists
        try {
            $pdo->exec("CREATE TABLE IF NOT EXISTS `users` (
              `id` int NOT NULL AUTO_INCREMENT,
              `full_name` varchar(200) NOT NULL,
              `email` varchar(200) NOT NULL,
              `username` varchar(200) NOT NULL,
              `password` varchar(255) NOT NULL,
              `role` varchar(50) NOT NULL DEFAULT 'school_admin',
              `tenant_id` int DEFAULT NULL,
              `phone` varchar(50) DEFAULT NULL,
              `is_active` tinyint(1) DEFAULT 1,
              `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
              PRIMARY KEY (`id`),
              UNIQUE KEY `uq_email` (`email`)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
        } catch (PDOException $ignored) {}

        // Insert or update super admin
        $existing = $pdo->prepare("SELECT id FROM users WHERE role='super_admin' LIMIT 1");
        $existing->execute();
        if (!$existing->fetch()) {
            $pdo->prepare("INSERT INTO users (full_name,email,username,password,role,tenant_id) VALUES (?,?,?,'','super_admin',NULL)")
                ->execute([$adminName, $adminEmail, $adminEmail]);
            $newId = $pdo->lastInsertId();
            $pdo->prepare("UPDATE users SET password=? WHERE id=?")->execute([$hashedPass, $newId]);
        } else {
            $pdo->prepare("UPDATE users SET full_name=?,email=?,username=?,password=? WHERE role='super_admin'")
                ->execute([$adminName, $adminEmail, $adminEmail, $hashedPass]);
        }
        $success[] = "Super admin account created: {$adminEmail}";

        // Populate pool (50 slots)
        TenantManager::ensurePoolTableExists($pdo);
        $poolResult = TenantManager::populatePool();
        $success[] = "Database pool populated: {$poolResult['added']} slots added, {$poolResult['skipped']} already existed.";

        // Create install lock file
        file_put_contents(__DIR__ . '/.installed', date('Y-m-d H:i:s'));

        header('Location: install.php?step=4&done=1');
        exit;

    } catch (Exception $e) {
        $errors[] = $e->getMessage();
        $step = 3;
    }
}

