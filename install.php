// ── Helpers ───────────────────────────────────────────────────────────
function checkExt(string $ext): string {
    return extension_loaded($ext)
        ? "<span style='color:#16a34a;font-weight:700;'>&#10003; {$ext}</span>"
        : "<span style='color:#dc2626;font-weight:700;'>&#10007; {$ext} — MISSING</span>";
}

function envGet(string $key, $default = ''): string {
    $f = ROOT_PATH . '/config/env.php';
    static $conf = null;
    if (!$conf && file_exists($f)) $conf = require $f;
    return (string)($conf[$key] ?? $default);
}

